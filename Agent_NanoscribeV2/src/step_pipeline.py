def main() -> None:
    parser = argparse.ArgumentParser(
        description="Slice a STEP file into Nanoscribe GWL toolpaths using exact BREP geometry.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  py src/step_pipeline.py model.step
  py src/step_pipeline.py model.step --job-name pillar_array
  py src/step_pipeline.py model.step --hatch 0.3 --slice 0.5 --contours 3
        """,
    )
    parser.add_argument("step_file", type=Path, help="Path to .step / .stp file")
    parser.add_argument("--job-name", type=str, default=None,
                        help="Override job name (default: STEP file stem)")
    parser.add_argument("--hatch", type=float, default=None,
                        help="Hatch spacing in µm (overrides PrintParameters.txt)")
    parser.add_argument("--slice", type=float, default=None,
                        help="Slice spacing in µm (overrides PrintParameters.txt)")
    parser.add_argument("--contours", type=int, default=None,
                        help="Number of contour passes (overrides PrintParameters.txt)")

    args = parser.parse_args()

    try:
        run_step_pipeline(
            step_path         = args.step_file,
            job_name          = args.job_name,
            hatch_override    = args.hatch,
            slice_override    = args.slice,
            contours_override = args.contours,
        )
    except FileNotFoundError as exc:
        print(f"[STEP] ERROR: {exc}")
        sys.exit(1)
    except Exception as exc:
        print(f"[STEP] ERROR: {exc}")
        import traceback
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
