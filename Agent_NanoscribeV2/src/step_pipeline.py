MIN_POLY_PTS        = 3     # minimum points to form a valid polygon


# ======================================================
# PARAMETER LOADING
# ======================================================

def _find_param_file(start: Path, max_levels: int = 5) -> Optional[Path]:
    """Walk up the directory tree looking for PrintParameters.txt."""
    current = start
    for _ in range(max_levels):
        candidate = current / "PrintParameters.txt"
        if candidate.exists():
            return candidate
        parent = current.parent
        if parent == current:
            break
        current = parent
    return None


def _load_params(param_file: Optional[Path]) -> Dict:
    """
    Load print parameters from file.  Applies defaults for any missing keys.
    Looks for hatch_spacing_um, slice_spacing_um, solid_contour_count.
    """
    raw: Dict = {}
    if param_file and param_file.exists():
        with param_file.open() as fh:
            for line in fh:
                line = line.strip()
                if ":" in line and not line.startswith("#"):
                    key, val = line.split(":", 1)
                    try:
                        raw[key.strip()] = float(val.strip())
                    except ValueError:
                        raw[key.strip()] = val.strip()

    return {
        "hatch_spacing_um":   float(raw.get("hatch_spacing_um",   DEFAULT_HATCH_UM)),
        "slice_spacing_um":   float(raw.get("slice_spacing_um",   DEFAULT_SLICE_UM)),
        "solid_contour_count": int(raw.get("solid_contour_count", DEFAULT_CONTOURS)),
        # pass through everything else for GWL serializer
        **{k: v for k, v in raw.items()
           if k not in ("hatch_spacing_um", "slice_spacing_um", "solid_contour_count")},
    }


