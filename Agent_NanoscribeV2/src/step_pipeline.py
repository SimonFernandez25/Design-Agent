"""
step_pipeline.py - STEP File Direct Slicing Pipeline

Parallel entry point to the Design Agent V2.  Accepts a STEP file and
produces the same outputs as the prompt-driven pipeline
(output.json, GWL files, renders) — without approximating geometry as
named-object primitives.

APPROACH — exact BREP cross-section slicing (pythonocc):
    BRepAlgoAPI_Section slices each solid at every Z plane → exact analytic
    edges (real circles, NURBS curves).  These are joined into closed wires,
    sampled to XY point arrays, and converted to Shapely polygons.  Hatch
    lines are generated by the same functions used in endpoint_generator_v2,
    so output.json is identical in schema to the prompt-pipeline output.

NOTHING in the existing pipeline is modified.
The only file this script reads from outside this repo is:
    Agent-Nanoscribe_Classification/src/step_loader.py  (load_step, extract_objects)

Usage:
    py src/step_pipeline.py path/to/file.step
    py src/step_pipeline.py path/to/file.step --job-name my_job
    py src/step_pipeline.py path/to/file.step --hatch 0.3 --slice 0.5 --contours 3
"""

